import React from "react";
import { Calculator, Binary, BrainCircuit, Sparkles } from "lucide-react";

export type BadgeType = "Computed" | "Statistical test" | "ML prediction" | "AI-generated" | string;

interface HonestBadgeProps {
  type?: BadgeType;
  className?: string;
}

export const HonestBadge: React.FC<HonestBadgeProps> = ({ type = "Computed", className = "" }) => {
  const norm = type?.toLowerCase() || "computed";

  if (norm.includes("stat")) {
    return (
      <span className={`badge-stats ${className}`} title="Derived directly from formal hypothesis testing or statistical model">
        <Binary className="w-3 h-3 text-purple-600 dark:text-purple-400" />
        Statistical test
      </span>
    );
  }

  if (norm.includes("ml") || norm.includes("predict")) {
    return (
      <span className={`badge-ml ${className}`} title="Generated by trained Machine Learning or Forecasting model">
        <BrainCircuit className="w-3 h-3 text-emerald-600 dark:text-emerald-400" />
        ML prediction
      </span>
    );
  }

  if (norm.includes("ai") || norm.includes("generated")) {
    return (
      <span className={`badge-ai ${className}`} title="Qualitative explanation or recommendation synthesized by LLM agent">
        <Sparkles className="w-3 h-3 text-amber-600 dark:text-amber-400" />
        AI-generated
      </span>
    );
  }

  // Default: Computed
  return (
    <span className={`badge-computed ${className}`} title="Deterministically calculated from SQL or mathematical formula">
      <Calculator className="w-3 h-3 text-blue-600 dark:text-blue-400" />
      Computed
    </span>
  );
};
