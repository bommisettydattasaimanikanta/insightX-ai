router = APIRouter(prefix="/reports", tags=["Reports & Exports"])

@router.get("/{dataset_id}/pdf")
def export_executive_summary_pdf(
    dataset_id: str,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    dataset, df = DatasetService.get_dataset_df(db, dataset_id)
    sem_model = db.query(SemanticModel).filter(
        SemanticModel.dataset_id == dataset_id,
        SemanticModel.version_num == dataset.current_version
    ).first()
    
    sem_dict = {
        "domain": sem_model.domain,
        "metrics": sem_model.metrics_json,
        "dimensions": sem_model.dimensions_json,
        "time_grains": sem_model.time_grains_json,
    } if sem_model else SemanticService.build_semantic_layer(df)

    insights = InsightEngine.generate_and_rank_insights(df, sem_dict)
    
    pdf_buffer = io.BytesIO()
    doc = SimpleDocTemplate(pdf_buffer, pagesize=letter, rightMargin=40, leftMargin=40, topMargin=40, bottomMargin=40)
    styles = getSampleStyleSheet()
    
    story = []
    
    # Title
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=22,
        leading=26,
        textColor=colors.HexColor('#4F46E5')
    )
    story.append(Paragraph(f"Executive Intelligence Report: {dataset.name}", title_style))
    story.append(Spacer(1, 10))
    
    # Subtitle & Metadata
    meta_text = f"Generated by InsightX AI | Domain: {sem_dict.get('domain', 'general').title()} | Rows: {len(df):,} | Columns: {len(df.columns)}"
    story.append(Paragraph(meta_text, styles['Normal']))
    story.append(Spacer(1, 15))
    
    # Executive Summary Paragraph
    story.append(Paragraph("<b>Executive Summary</b>", styles['Heading2']))
    summary_text = (
        f"This autonomous audit synthesizes key operational metrics, trends, and risk vectors across "
        f"{len(df):,} records. Analysis reveals actionable opportunities across segmentation and performance."
    )
    story.append(Paragraph(summary_text, styles['Normal']))
    story.append(Spacer(1, 15))
    
    # Ranked Insights
    story.append(Paragraph("<b>Ranked Strategic Insights</b>", styles['Heading2']))
    for ins in insights[:4]:
        headline = f"<b>• {ins['headline']}</b> [{ins.get('tag', 'Computed')}]"
        story.append(Paragraph(headline, styles['Normal']))
        why = f"<i>Impact:</i> {ins['why_it_matters']} <i>Action:</i> {ins.get('suggested_action', 'Monitor')}"
        story.append(Paragraph(why, styles['BodyText']))
        story.append(Spacer(1, 8))
        
    doc.build(story)
    pdf_buffer.seek(0)
    
    return Response(
        content=pdf_buffer.getvalue(),
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename=Executive_Summary_{dataset.name}.pdf"}
    )

